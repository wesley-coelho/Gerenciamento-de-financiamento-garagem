    private void txtCEPFinanciamentoKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtCEPFinanciamentoKeyPressed
        // TODO add your handling code here:
        
        
        if( !Character.isDigit(evt.getKeyChar())){
            if( this.txtCEPFinanciamento.getText().length() > 0){
                this.txtCEPFinanciamento.setText(this.txtCEPFinanciamento.getText().substring(0, this.txtCEPFinanciamento.getText().length()-1));
                this.txtCEPFinanciamento.setToolTipText("Digite apenas números");
            }
        }else{
            int  letraLen = this.txtCEPFinanciamento.getText().length();
            if( letraLen == 5){
                this.txtCEPFinanciamento.setText(this.txtCEPFinanciamento.getText() + "-");
            }

            if(letraLen > 8 ){
                this.txtCEPFinanciamento.setText(this.txtCEPFinanciamento.getText().substring(0, 8));
            }

        }
    }//GEN-LAST:event_txtCEPFinanciamentoKeyPressed

