    private void txtCPFFinanciamentoFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtCPFFinanciamentoFocusLost
        // TODO add your handling code here:
        if( this.txtCPFFinanciamento.getText().length() < 11 && !this.txtCPFFinanciamento.getText().isBlank() ){
             JOptionPane.showMessageDialog(this, "CPF inválido");
            this.txtCPFFinanciamento.requestFocus();
          
        }else if(!this.txtCPFFinanciamento.getText().isBlank()&& this.txtCPFFinanciamento.getText().length() == 11 ){
                if( Validacao.validaCPF(this.txtCPFFinanciamento.getText()) == false ){
                    JOptionPane.showMessageDialog(this, "CPF inválido");             
                    this.txtCPFFinanciamento.requestFocus();
                    this.txtCPFFinanciamento.setText("");
                }
        }
       
        
    }//GEN-LAST:event_txtCPFFinanciamentoFocusLost

